import json
from app import extract

with open("sample_claims.json", encoding="utf-8") as f:
    cases=json.load(f)

type_correct=0
conflict_correct=0
rows=[]
for case in cases:
    out=extract(case["text"])
    type_ok=out["claim_type"] == case["expected_type"]
    conflict_ok=bool(out["conflicts"]) == case["expect_conflict"]
    type_correct += type_ok
    conflict_correct += conflict_ok
    rows.append({
        "id":case["id"],
        "expected_type":case["expected_type"],
        "predicted_type":out["claim_type"],
        "type_match":type_ok,
        "expected_conflict":case["expect_conflict"],
        "predicted_conflict":bool(out["conflicts"]),
        "conflict_match":conflict_ok,
        "triage":out["triage_category"]
    })
result={
    "test_count":len(cases),
    "claim_type_exact_match_count":type_correct,
    "claim_type_exact_match_rate":round(type_correct/len(cases),3),
    "conflict_detection_match_count":conflict_correct,
    "conflict_detection_match_rate":round(conflict_correct/len(cases),3),
    "note":"Small synthetic smoke-test evaluation. Results are generated by running evaluate.py; they are not a production benchmark.",
    "cases":rows
}
with open("evaluation_results.json","w",encoding="utf-8") as f: json.dump(result,f,indent=2)
print(json.dumps({k:v for k,v in result.items() if k!="cases"},indent=2))
print("\\nPer-case results:")
for r in rows: print(r)
